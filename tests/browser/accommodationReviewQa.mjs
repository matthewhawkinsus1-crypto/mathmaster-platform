import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
assert.ok(process.env.FIRESTORE_EMULATOR_HOST, 'Run through Firebase emulators:exec against a demo project.');
const processes = [];
const launch = (args) => { const child = spawn(process.execPath, args, { stdio: ['ignore', 'inherit', 'inherit'] }); processes.push(child); return child; };
const wait = async (url) => { for (let i = 0; i < 100; i++) { try { if ((await fetch(url)).ok) return; } catch { /* not ready */ } await new Promise((r) => setTimeout(r, 200)); } throw new Error(`Service failed: ${url}`); };
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
let browser;
try {
  launch(['tests/browser/accommodationReviewBridge.mjs']);
  launch(['node_modules/vite/bin/vite.js', '--config', 'tests/browser/emulator/vite.config.mjs', '--host', '127.0.0.1', '--port', '5199', '--strictPort']);
  await wait('http://127.0.0.1:5197/seed');
  await wait('http://127.0.0.1:5199/tests/browser/accommodationReview.html');
  browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined });
  for (const width of [1366, 390]) {
    await fetch('http://127.0.0.1:5197/seed');
    const context = await browser.newContext({ viewport: { width, height: 900 } });
    const page = await context.newPage(); const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    await page.route('**/*', (route) => ['127.0.0.1', 'localhost'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort());
    await page.goto('http://127.0.0.1:5199/tests/browser/accommodationReview.html');
    await page.locator('[data-ready]').waitFor();
    await page.getByRole('button', { name: 'Student assignments', exact: true }).click();
    await page.getByRole('tab', { name: /Upcoming/ }).click();
    assert.match(await page.locator('body').innerText(), /16 of 20 questions required/);
    await page.getByRole('button', { name: 'Teacher review', exact: true }).click();
    await page.getByText('Retroactive Accommodation Review', { exact: true }).click();
    await page.getByLabel('Source descriptor', { exact: true }).fill('Synthetic documented reference');
    await page.getByLabel('Documented effective date', { exact: true }).fill('2026-08-01');
    await page.getByLabel('Historical range from', { exact: true }).fill('2026-09-01');
    await page.getByLabel('Historical range through', { exact: true }).fill('2026-09-30');
    await page.getByRole('button', { name: 'Preview historical assignments', exact: true }).click();
    const row = page.getByRole('region', { name: 'Review Synthetic historical assignment', exact: true });
    await row.waitFor();
    const manual = page.getByRole('region', { name: 'Review Synthetic secure assignment', exact: true });
    assert.match(await manual.innerText(), /Previous grade: Manual review needed\. Proposed grade: Manual review needed/);
    assert.equal(await manual.getByRole('button', { name: 'Approve correction', exact: true }).count(), 0);
    assert.match(await row.innerText(), /proposed 16 of 20/);
    assert.equal(await row.getByRole('button', { name: 'Approve correction', exact: true }).isDisabled(), true);
    await page.getByLabel('I confirm my authority', { exact: false }).check();
    await row.getByLabel('Approve this assignment', { exact: false }).check();
    await row.getByRole('button', { name: 'Approve correction', exact: true }).click();
    await page.getByText('Correction saved with a new audit event.', { exact: false }).waitFor();
    assert.match(await row.innerText(), /not-requested/);
    await page.getByRole('button', { name: 'Student grades', exact: true }).click();
    assert.match(await page.locator('body').innerText(), /16 of 20 questions required/);
    await page.getByRole('button', { name: 'Hide grade', exact: true }).click();
    assert.doesNotMatch(await page.locator('body').innerText(), /Approved grade:/, 'hiding grades also hides the approved correction grade');
    await page.getByRole('button', { name: 'Family summary', exact: true }).click();
    await page.getByText('Family workload summary', { exact: true }).click();
    const family = await page.getByRole('textbox', { name: 'Family workload summary', exact: true }).inputValue();
    assert.match(family, /Retroactive grade correction/);
    assert.match(family, /Approved grade: 6%/);
    assert.doesNotMatch(family, /IEP|504|disability|inclusion|documented reference/i);
    await page.getByRole('button', { name: 'Student held grades', exact: true }).click();
    assert.match(await page.locator('body').innerText(), /Pending Grade/i);
    assert.match(await page.locator('body').innerText(), /16 of 20 questions required/);
    assert.doesNotMatch(await page.locator('body').innerText(), /Approved grade:/, 'held teacher feedback keeps correction percentages private');
    await page.getByRole('button', { name: 'Teacher review', exact: true }).click();
    await page.getByText('Retroactive Accommodation Review', { exact: true }).click();
    // Remounting requires a fresh preview and fresh confirmations.
    await page.getByLabel('Source descriptor', { exact: true }).fill('Synthetic documented reference');
    await page.getByLabel('Documented effective date', { exact: true }).fill('2026-08-01');
    await page.getByLabel('Historical range from', { exact: true }).fill('2026-09-01');
    await page.getByLabel('Historical range through', { exact: true }).fill('2026-09-30');
    await page.getByRole('button', { name: 'Preview historical assignments', exact: true }).click();
    await row.waitFor();
    await row.getByRole('button', { name: 'Request Google Classroom sync', exact: true }).click();
    await page.getByText('Classroom sync requested.', { exact: false }).waitFor();
    await row.getByRole('button', { name: 'Preview reversal', exact: true }).click();
    await row.getByLabel('Second confirmation:', { exact: false }).waitFor();
    await page.getByLabel('I confirm my authority', { exact: false }).check();
    await row.getByLabel('Approve this assignment', { exact: false }).check();
    assert.equal(await row.getByRole('button', { name: 'Approve reversal', exact: true }).isDisabled(), true);
    await row.getByLabel('Second confirmation:', { exact: false }).check();
    await row.getByRole('button', { name: 'Approve reversal', exact: true }).click();
    await page.getByText('Correction saved with a new audit event.', { exact: false }).waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), true);
    assert.deepEqual(errors, []);
    await context.close();
    console.log(`Synthetic accommodation approval/reversal, student and family journey ${width}px passed`);
  }
} finally { await browser?.close(); for (const child of processes) child.kill('SIGTERM'); }
