test('expectedValues carries the answer in every form a hint could leak', () => {
  for (const item of ITEMS) {
    const values = systems.expectedValues(item.question);
    if (item.answer.outcome === 'point') {
      const [x] = numberForms(item.answer.x);
      const [y] = numberForms(item.answer.y);
      assert.ok(values.includes(x) && values.includes(y), `${item.name}: bare coordinates ${x}, ${y} in ${JSON.stringify(values)}`);
      assert.ok(values.includes(`(${x}, ${y})`), `${item.name}: the pair (${x}, ${y})`);
    }
    if (item.question.type === 'systemsWorkspace' || item.question.toolId === 'systemsWorkspace' || item.answer.outcome !== 'point') {
      // Every outcome phrase, whichever is right, so the guard's silence tells nothing.
      systems.OUTCOME_PHRASES.forEach((phrase) => assert.ok(values.includes(phrase), `${item.name}: ${phrase}`));
    }
  }
});

test('hints: 2–4 sentences from this problem, none of which names or narrows the answer', () => {
  let specific = 0;
  for (const item of ITEMS) {
    const hints = systems.hints(item.question);
    assert.ok(hints.length >= 2 && hints.length <= 4, `${item.name}: ${hints.length} hints`);
    const guard = guardFor(item);
    hints.forEach((hint) => {
      assert.equal(typeof hint, 'string');
      assert.equal(hintRevealsAnswer(hint, guard), false, `${item.name}: "${hint}" leaks the answer`);
      systems.OUTCOME_PHRASES.forEach((phrase) => assert.ok(!hint.toLowerCase().includes(phrase), `${item.name}: "${hint}" names an outcome`));
    });
    // Built from this problem: at least one hint quotes one of its equations.
    if (hints.some((hint) => /\$[^$]*=[^$]*\$/.test(hint))) specific += 1;
    // The platform ladder carries them (after the leak guard).
    const ladder = buildQuestionHints(item.question).filter((hint) => hint.source === 'family').map((hint) => hint.text);
    hints.forEach((hint) => assert.ok(ladder.includes(hint), `${item.name}: buildQuestionHints keeps "${hint}"`));
  }
  assert.ok(specific >= ITEMS.length * 0.8, `most hint ladders quote the problem's own equations (${specific}/${ITEMS.length})`);
});

test('hints read what the student sees, not the outcome: every mixed-case system gets the same advice about cancelling', () => {
  const mixed = ITEMS.filter((item) => item.kind === 'algebraic/mixed');
  const special = 'If both variables cancel, decide whether the statement that is left is true or false';
  for (const item of mixed) {
    assert.ok(systems.hints(item.question).some((hint) => hint.includes(special)), `${item.name} (${item.answer.outcome})`);
  }
  // A one-solution `system` item is never told about cancelling variables.
  const plain = ITEMS.find((item) => item.kind === 'elimination/system');
  assert.ok(!systems.hints(plain.question).some((hint) => hint.includes(special)));
});

test('a hint whose numbers coincide with the answer falls back to a wording without them', () => {
  // 2x - y = 0 holds the 2 of (1, 2): the quoted equation would name a coordinate.
  const question = { type: 'system', prompt: 'Solve the system.', equationsLatex: ['x + y = 3', '2x - y = 0'], solution: [1, 2] };
  const hints = systems.hints(question);
  assert.equal(hints.length, 4);
  hints.forEach((hint) => assert.equal(hintRevealsAnswer(hint, ['1', '2', '(1, 2)']), false, hint));
  assert.ok(hints.some((hint) => hint.includes('$y$-terms') && hint.includes('opposites')), 'still names this problem’s move');
});

test('similarProblem: a fully worked sibling with different numbers and a different, correct answer', () => {
  for (const item of ITEMS) {
    const example = systems.similarProblem(item.question, { seed: 0 });
    assert.ok(example, `${item.name}: a sibling`);
    assert.ok(example.prompt && example.steps.length >= 4 && example.answer, item.name);
    // Its answer, recomputed here from its own equations.
    const rows = siblingSystem(example);
    assert.equal(rows.length, 2, `${item.name}: the sibling shows two equations`);
    const solved = solveRows(rows);
    assert.notEqual(solved.det, 0, `${item.name}: one solution`);
    const pair = example.answer.match(/^\((-?\d+), (-?\d+)\)$/);
    assert.ok(pair, `${item.name}: answer "${example.answer}" is a pair`);
    const point = { x: Number(pair[1]), y: Number(pair[2]) };
    assert.ok(near(point.x, solved.x) && near(point.y, solved.y), `${item.name}: ${example.answer} solves the sibling`);
    assertStepsTrue(example, point, item.name);
    // Never this problem: a different answer, and no step names this one.
    if (item.answer.outcome === 'point') assert.ok(!(near(point.x, item.answer.x) && near(point.y, item.answer.y)), `${item.name}: a different answer`);
    const guard = guardFor(item);
    [example.prompt, ...example.steps, example.answer].forEach((piece) => assert.equal(hintRevealsAnswer(piece, guard), false, `${item.name}: "${piece}" names this answer`));
    // Deterministic from the seed, different for another seed.
    assert.deepEqual(systems.similarProblem(item.question, { seed: 0 }), example);
    assert.notDeepEqual(systems.similarProblem(item.question, { seed: 1 }), example, `${item.name}: another seed, another sibling`);
    assert.ok(buildSimilarWorkedExample(item.question), `${item.name}: the platform offers it`);
  }
});

test('the sibling is the same kind of problem', () => {
  const kindOf = (item) => systems.similarProblem(item.question, { seed: 2 });
  for (const item of ITEMS) {
    const example = kindOf(item);
    if (item.kind.startsWith('substitution/')) assert.match(example.steps[0], /already gives \$y = /, item.name);
    if (item.kind === 'legacy/generator') assert.match(example.steps[0], /set the right sides equal/, item.name);
    if (item.kind.startsWith('elimination/')) assert.match(example.steps[0], /^Line up the equations/, item.name);
    if (item.kind.startsWith('workspace/linear')) assert.match(example.prompt, /^Graph /, item.name);
    if (item.kind === 'workspace/matrix') assert.match(example.prompt, /augmented matrix/, item.name);
    if (item.kind === 'algebraic/substitution') assert.match(example.prompt, /by substitution/, item.name);
  }
});

test('backUpQuestion: two choices about this problem’s first move, the conventional one correct, no answer in it', () => {
  let specific = 0;
  for (const item of ITEMS) {
    const step = systems.backUpQuestion(item.question);
    assert.ok(step, item.name);
    assert.equal(step.options.length, 2, item.name);
    assert.notEqual(step.options[0], step.options[1], item.name);
    assert.ok(step.options.includes(step.correct), `${item.name}: the correct option is offered`);
    const guard = guardFor(item);
    [step.prompt, ...step.options].forEach((piece) => assert.equal(hintRevealsAnswer(piece, guard), false, `${item.name}: "${piece}"`));
    assert.ok(!/\$/.test(step.prompt + step.options.join('')), `${item.name}: plain text (the buttons do not render math)`);
    if (!step.prompt.includes('Does the solution of a system')) specific += 1;
    assert.equal(backUpStepFor(item.question).source, 'family', `${item.name}: the inclusion step uses it`);
  }
  assert.ok(specific >= ITEMS.length * 0.9, `most back-up steps are about this problem (${specific}/${ITEMS.length})`);
});

test('the back-up step points the right way for each first move', () => {
  const opposite = systems.backUpQuestion({ type: 'system', equationsLatex: ['2x + 3y = 12', '5x - 3y = 9'], solution: [3, 2] });
  assert.equal(opposite.correct, 'Add the two equations');
  const same = systems.backUpQuestion({ type: 'system', equationsLatex: ['4x + 3y = 25', '2x + 3y = 17'], solution: [4, 3] });
  assert.equal(same.correct, 'Subtract the second equation from the first');
  const multiply = systems.backUpQuestion({ type: 'system', equationsLatex: ['x + 2y = 7', '3x - 5y = -1'], solution: [3, 2] });
  assert.equal(multiply.correct, 'Every term, on both sides');
  const substitution = systems.backUpQuestion({ type: 'system', equationsLatex: ['y = 2x - 1', '3x + 2y = 33'], solution: [5, 9] });
  assert.equal(substitution.correct, 'Replace y with (2x - 1)');
  const setEqual = systems.backUpQuestion({ type: 'system', equationsLatex: ['y = -4x + 23', 'y = 4x - 25'], solution: [6, -1] });
  assert.equal(setEqual.correct, 'Set -4x + 23 equal to 4x - 25');
});
