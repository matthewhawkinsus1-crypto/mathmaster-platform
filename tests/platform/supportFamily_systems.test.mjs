  const resolved = resolveFamilyQuestionInstance({ question: slot, assignmentId: `a-systems-${label}`, storageIndex: 0, allocation: allocation(seat) });
  assert.equal(resolved.error, null, `${familyId} resolves`);
  const { values } = resolved.instance;
