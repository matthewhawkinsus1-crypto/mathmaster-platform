const guardFor = (item) => [...systems.expectedValues(item.question), ...independentForms(item.answer)];

/* --------------------------------------------- checking a worked sibling */

const mathSegments = (value) => [...String(value).matchAll(/\$([^$]+)\$/g)].map((match) => match[1]);
const plainMath = (latex) => latexToExpression(latex).replace(/·/g, '*');
// Every $…$ equation (or chain a = b = c) in the worked steps is TRUE at the
// sibling's own solution: the work, not only the answer, is right.
const assertStepsTrue = (example, point, label) => {
  const scope = { x: point.x, y: point.y };
  let checked = 0;
  example.steps.forEach((step) => mathSegments(step).forEach((segment) => {
    const parts = segment.split('=');
    if (parts.length < 2) return;
    const values = parts.map((part) => Number(evaluate(plainMath(part), scope)));
    values.slice(1).forEach((value) => assert.ok(near(value, values[0]), `${label}: "${segment}" is not true at (${point.x}, ${point.y}) in "${step}"`));
    checked += 1;
  }));
  assert.ok(checked >= 3, `${label}: the worked steps show their equations`);
};
// The sibling's own system, read back from its prompt and solved here.
const siblingSystem = (example) => {
  const rows = [...example.prompt.matchAll(/\[(-?\d+)\s+(-?\d+)\s*\|\s*(-?\d+)\]/g)].map((match) => match.slice(1).map(Number));
  if (rows.length === 2) return rows.map(([a, b, c]) => ({ a, b, c }));
  return mathSegments(example.prompt).filter((segment) => segment.includes('=')).map((segment) => linearEquationCoefficients(plainMath(segment)));
};
const solveRows = ([r1, r2]) => {
  const det = r1.a * r2.b - r1.b * r2.a;
  return { x: (r1.c * r2.b - r1.b * r2.c) / det, y: (r1.a * r2.c - r1.c * r2.a) / det, det };
};

