const near = (a, b) => Math.abs(a - b) < 1e-6;
// Every way the test itself would write a coordinate: integer, a/b, decimals.
const numberForms = (value) => {
  const forms = new Set([String(Math.round(value * 1e4) / 1e4), String(Math.round(value * 100) / 100), String(Math.round(value * 10) / 10)]);
  for (let d = 1; d <= 12; d += 1) {
    const n = Math.round(value * d);
    if (near(n / d, value)) { forms.add(d === 1 ? String(n) : `${n}/${d}`); break; }
  }
  return [...forms];
};
const independentForms = (answer) => {
  if (!answer || answer.outcome !== 'point') return ['no solution', 'infinitely many'];
  const xs = numberForms(answer.x);
  const ys = numberForms(answer.y);
  return [...xs, ...ys, `(${xs[0]}, ${ys[0]})`, `(${xs[0]},${ys[0]})`];
};
const fromSolve = (solved) => (solved.type === 'one' ? { outcome: 'point', x: solved.x, y: solved.y } : { outcome: solved.type });

