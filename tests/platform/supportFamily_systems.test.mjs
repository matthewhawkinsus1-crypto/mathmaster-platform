  // …while a hand-authored multiAnswer system with no family id is recognised by content.
  assert.equal(systems.matches({ type: 'multiAnswer', prompt: 'Solve the system $x + y = 5$ and $x - y = 1$.', answerFields: [{ id: 'xy', label: '$(x, y)$ =', answer: '(3, 2)' }] }), true);
