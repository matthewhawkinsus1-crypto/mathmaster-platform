// Which pull requests run which workflow.
//
// .github/workflows/ci.yml is the one entry point for pull requests and for
// pushes to main, and its "CI gate" job is the one check a pull request must
// pass. It calls every workflow that guards main. A workflow named here runs
// on a pull request only when the pull request changes a file its patterns
// reach; full-platform-suite.yml, which is not named, runs on every one. A
// push to main, a manual run, and any change to CI itself (RUN_EVERYTHING)
// run them all.
//
// The patterns are the `paths` each workflow had when it triggered itself,
// and they are read the way GitHub reads `paths`: in order, the last pattern
// that matches decides, and `!` excludes. `*` stays inside one folder and `**`
// crosses folders, dotfiles included (path.matchesGlob skips dotfiles, so it is
// not used). GitHub gives `?`, `+` and `[]` meanings of its own; no pattern
// uses them, and tests/platform/ciAreas.test.mjs keeps it that way.

