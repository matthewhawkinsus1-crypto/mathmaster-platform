const escape = (text) => text.replace(/[.+?^${}()|[\]\\]/g, '\\$&');

/** A `paths` pattern as a regular expression: `**` crosses folders, `*` does not. */
export const patternRegExp = (pattern) => new RegExp(`^${pattern.split('**').map((part) => part.split('*').map(escape).join('[^/]*')).join('.*')}$`);

/** GitHub's rule: patterns in order, the last one that matches decides. */
export const reachedBy = (file, patterns) => {
  let reached = false;
  for (const pattern of patterns) {
    const negated = pattern.startsWith('!');
    if (patternRegExp(negated ? pattern.slice(1) : pattern).test(file)) reached = !negated;
  }
  return reached;
};

/**
 * For each workflow in `areas`, whether a change to `files` runs it. `files`
 * is null when the change is unknown (a push to main, a manual run, a diff
 * that could not be read): then everything runs.
 */
export const changedAreas = (files, areas = CI_AREAS) => {
  const everything = files === null || files.some((file) => reachedBy(file, RUN_EVERYTHING));
  return Object.fromEntries(Object.entries(areas)
    .map(([workflow, patterns]) => [workflow, everything || files.some((file) => reachedBy(file, patterns))]));
};

/** The first changed file that runs `workflow`, for the run's summary; null if none does. */
export const firstReaching = (files, patterns) => (files || []).find((file) => reachedBy(file, patterns)) ?? null;
